"""One-page incident report, as a PDF.

Built with Pillow, which is already a dependency for thumbnails, so this adds no library.
The page is raster rather than selectable text: the point is a sheet an estate manager can
hand to police, a guest or a residents' association, not a document anyone will edit.
"""
from __future__ import annotations

from io import BytesIO
from pathlib import Path
from typing import Any

from PIL import Image, ImageDraw, ImageFont

PAGE = (1240, 1754)  # A4 at ~150 dpi, white
MARGIN = 90
INK = (17, 20, 28)
MUTED = (90, 96, 110)
RULE = (210, 214, 222)

_FONT_CANDIDATES = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "C:/Windows/Fonts/segoeui.ttf",
    "C:/Windows/Fonts/arial.ttf",
)


def _font(size: int) -> ImageFont.ImageFont:
    for path in _FONT_CANDIDATES:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size)
            except Exception:  # noqa: BLE001
                continue
    try:
        return ImageFont.load_default(size)  # Pillow >= 10.1
    except Exception:  # noqa: BLE001
        return ImageFont.load_default()


def _text(value: Any, limit: int = 300) -> str:
    """Everything here can come from a device or the network; keep it printable."""
    if value is None:
        return "-"
    return str(value).replace("\r", " ").replace("\n", " ").strip()[:limit] or "-"


def _time(ts: Any) -> str:
    try:
        import datetime as _dt

        return _dt.datetime.fromtimestamp(float(ts)).strftime("%Y-%m-%d %H:%M:%S")
    except Exception:  # noqa: BLE001
        return "-"


def render_page(event: dict[str, Any], thumb_path: str | None, site: str = "") -> Image.Image:
    """The report as an image, so it can be inspected or saved in another format."""
    page = Image.new("RGB", PAGE, "white")
    draw = ImageDraw.Draw(page)
    y = MARGIN

    draw.text((MARGIN, y), "Incident report", font=_font(52), fill=INK)
    y += 76
    draw.text(
        (MARGIN, y),
        _text(site, 80) + "  ·  event #" + _text(event.get("id"), 12),
        font=_font(26),
        fill=MUTED,
    )
    y += 60
    draw.line([(MARGIN, y), (PAGE[0] - MARGIN, y)], fill=RULE, width=2)
    y += 40

    rows = [
        ("Camera", _text(event.get("camera_name") or event.get("camera_id"), 120)),
        ("Time", _time(event.get("start_ts"))),
        ("Type", _text(event.get("event_type"), 40)),
        ("Objects", ", ".join(event.get("objects") or []) or "-"),
        ("Confidence", f"{float(event.get('max_conf') or 0):.2f}" if event.get("max_conf") else "-"),
        ("Duration", f"{float(event.get('duration') or 0):.1f}s" if event.get("duration") else "-"),
        ("Plate", _text(event.get("plate"), 24)),
        ("Status", "resolved" if event.get("resolved") else "acknowledged" if event.get("acknowledged") else "unhandled"),
        ("Assignee", _text(event.get("assignee"), 80)),
    ]
    for label, value in rows:
        draw.text((MARGIN, y), label, font=_font(24), fill=MUTED)
        draw.text((MARGIN + 260, y), value, font=_font(28), fill=INK)
        y += 48

    # Thumbnail, if the file is still on disk. Its height is clamped to whatever vertical
    # space is left after the metadata rows, so a long summary or a tall crop cannot push
    # content off the bottom of the page.
    bottom_limit = PAGE[1] - MARGIN - 60
    image_box_h = max(120, min(560, bottom_limit - y - 260))
    if thumb_path and Path(thumb_path).exists():
        try:
            shot = Image.open(thumb_path).convert("RGB")
            shot.thumbnail((PAGE[0] - 2 * MARGIN, image_box_h))
            y += 20
            page.paste(shot, (MARGIN, y))
            y += shot.height + 26
        except Exception:  # noqa: BLE001
            pass

    if event.get("summary"):
        draw.text((MARGIN, y), "Summary", font=_font(24), fill=MUTED)
        y += 38
        words, line = str(event["summary"]).split(), ""
        for word in words:
            if y > bottom_limit - 60:
                break
            trial = (line + " " + word).strip()
            if draw.textlength(trial, font=_font(30)) > PAGE[0] - 2 * MARGIN:
                draw.text((MARGIN, y), line, font=_font(30), fill=INK)
                y += 40
                line = word
            else:
                line = trial
        if line and y <= bottom_limit - 60:
            draw.text((MARGIN, y), line, font=_font(30), fill=INK)
            y += 40

    footer = "Generated by SmartCam. Retain and handle this record in line with your data protection policy."
    draw.text((MARGIN, PAGE[1] - MARGIN), footer, font=_font(20), fill=MUTED)

    return page


def build_report(event: dict[str, Any], thumb_path: str | None, site: str = "") -> bytes:
    buf = BytesIO()
    render_page(event, thumb_path, site).save(buf, format="PDF", resolution=150.0)
    return buf.getvalue()
